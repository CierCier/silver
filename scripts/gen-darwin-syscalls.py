#!/usr/bin/env python3
"""
Generate std/sys/darwin_syscalls.ag, the Darwin (macOS) syscall numbers,
from the macOS SDK's <sys/syscall.h>.

Usage:
    python3 scripts/gen-darwin-syscalls.py [syscall.h] [output.ag]

The header defaults to `$(xcrun --show-sdk-path)/usr/include/sys/syscall.h`
and the output to std/sys/darwin_syscalls.ag. Apple does not promise that
these numbers stay stable across releases; std itself reaches the kernel
through libSystem (std/sys/os_macos.ag) and uses them only for the raw
`syscallN` wrappers in std/sys/syscall.ag.
"""

import re
import subprocess
import sys
from datetime import date
from pathlib import Path


def default_header() -> Path:
    sdk = subprocess.check_output(["xcrun", "--show-sdk-path"], text=True).strip()
    return Path(sdk) / "usr/include/sys/syscall.h"


def main() -> int:
    header = Path(sys.argv[1]) if len(sys.argv) > 1 else default_header()
    root = Path(__file__).resolve().parent.parent
    output = Path(sys.argv[2]) if len(sys.argv) > 2 else root / "std/sys/darwin_syscalls.ag"

    entries = []
    for line in header.read_text().splitlines():
        match = re.match(r"#define\s+SYS_(\w+)\s+(\d+)\s*$", line)
        if match and match.group(1) != "MAXSYSCALL":
            entries.append((match.group(1).upper(), int(match.group(2))))
    if not entries:
        print(f"no SYS_* numbers found in {header}", file=sys.stderr)
        return 1

    lines = [
        "// Auto-generated by scripts/gen-darwin-syscalls.py",
        f"// Source: macOS SDK <sys/syscall.h> ({len(entries)} syscalls)",
        f"// Generated: {date.today().isoformat()}",
        "// DO NOT EDIT -- regenerate with:",
        "//   python3 scripts/gen-darwin-syscalls.py",
        "",
        "if (@cfg(os.macos)) {",
        "/// Darwin syscall numbers (`SYS_<name>` upper-cased) for the raw",
        "/// `syscallN` wrappers in std.sys.syscall. Apple does not keep them",
        "/// stable across releases; std reaches the kernel through libSystem.",
        "enum SYSCALL {",
    ]
    lines += [f"    {name} = {number};" for name, number in entries]
    lines += ["}", "}", ""]
    output.write_text("\n".join(lines))
    print(f"wrote {len(entries)} syscalls to {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
